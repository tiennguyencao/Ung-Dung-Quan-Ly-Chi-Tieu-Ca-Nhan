export function translateText(text, language = 'en') {
  if (language !== 'vi' || typeof text !== 'string') return text;
  const exact = VI_TRANSLATIONS[text];
  if (exact) return exact;

  // Preserve user-entered values while localizing variable backend messages.
  let match = text.match(/^A category named "(.+)" already exists\.$/);
  if (match) return `Danh mục tên "${match[1]}" đã tồn tại.`;

  match = text.match(/^Can't delete "(.+)" — (\d+) transaction(s?) still use it\. Reassign or delete them first\.$/);
  if (match) {
    const count = Number(match[2]);
    const transactionNoun = count === 1 ? 'giao dịch vẫn đang sử dụng' : 'giao dịch vẫn đang sử dụng';
    return `Không thể xóa "${match[1]}" — ${count} ${transactionNoun}. Hãy chuyển các giao dịch sang danh mục khác hoặc xóa chúng trước.`;
  }

  match = text.match(/^Invalid (.+)\.$/);
  if (match) return `Giá trị ${match[1]} không hợp lệ.`;

  match = text.match(/^(.+) is required$/);
  if (match) {
    const field = {
      Name: 'tên', Email: 'email', Password: 'mật khẩu', Amount: 'số tiền',
      Category: 'danh mục', Date: 'ngày', Month: 'tháng', 'Category name': 'tên danh mục',
    }[match[1]];
    if (field) return `Vui lòng nhập ${field}.`;
  }
  return text;
}

export function translateCategoryName(name, language = 'en') {
  if (!name || language !== 'en') return name;
  const categories = {
    'Ăn uống': 'Food & Dining',
    'Di chuyển': 'Transportation',
    'Hóa đơn': 'Bills',
    'Giải trí': 'Entertainment',
    Lương: 'Salary',
    Thưởng: 'Bonus',
  };
  return categories[name] || name;
}
